"""Fusion experiment: can we get the 'winning version' gains WITHOUT knowing the answer?

Reuses rewrites already generated by strategy_experiment.py (and the saved paraphrases),
so no Ollama calls happen here. For each strategy it combines the original description and
its rewrites into ONE ranking, using only information available at search time:

- interleave: round-robin over the queries' result lists (orig #1, rewrite1 #1, ..., then #2s),
  skipping images already listed. Works because a winning rewrite usually puts the target at #1.
- interleave (orig x2): the original gets two slots per round.
- z-max / z-min: standardize each query's 50k scores, then take the best / worst per image.
- weighted mean embedding / RRF: the original counts ORIGINAL_WEIGHTS times.

Open in VS Code and click Run. Results go to runs/fusion/<timestamp>/.
"""
from datetime import datetime, timezone
import csv
import json
from pathlib import Path
import random

import torch

from agentir.cache import load_cache, read_json
from agentir.evaluation import matched_queries
from agentir.retrieval import BlipRetriever, ranks_for_targets
from paraphrase_experiment import positions, recall


# SETTINGS
STRATEGY_RUN = None          # Folder under runs/strategies/; None = the most recent run.
FULL_PARAPHRASE = True       # Also evaluate paraphrase on all 2,064 (saved rewrites cover all).
ORIGINAL_WEIGHTS = [2, 3]    # Weighted fusions: the original counts this many times.
K_VALUES = [1, 10, 100]
RRF_CONSTANT = 60
DEVICE = "cpu"
CPU_THREADS = 4
SAVED_PARAPHRASES = "results/paraphrase/qwen3_4b_rewrites.json"


INTERLEAVE_DEPTH = 1000     # Build the merged list this far; deeper targets count as rank DEPTH + 1.


def interleave_rank(scores, target_id, weights):
    """Rank of the target in a weighted round-robin of the queries' result lists.

    Each round, query q (original first) adds its next weights[q] images that are not
    already in the merged list. Only the top of each list can matter for R@K <= 100.
    """
    lists = torch.topk(scores, min(INTERLEAVE_DEPTH, scores.shape[1]), dim=1).indices.tolist()
    merged, seen, pointer = 0, set(), [0] * len(lists)
    while merged < INTERLEAVE_DEPTH and any(p < len(l) for p, l in zip(pointer, lists)):
        for q, items in enumerate(lists):
            for _ in range(weights[q]):
                while pointer[q] < len(items) and items[pointer[q]] in seen:
                    pointer[q] += 1
                if pointer[q] < len(items):
                    image = items[pointer[q]]
                    pointer[q] += 1
                    seen.add(image)
                    merged += 1
                    if image == target_id:
                        return merged
    return INTERLEAVE_DEPTH + 1


def methods_for(vectors, images, target_id):
    """Every label-free combination of [original, *rewrites] -> the target's rank."""
    scores = vectors @ images.T
    pos = positions(scores)
    n = len(vectors)
    z = (scores - scores.mean(1, keepdim=True)) / scores.std(1, keepdim=True)
    out = {
        "interleave": interleave_rank(scores, target_id, [1] * n),
        "interleave (orig x2)": interleave_rank(scores, target_id, [2] + [1] * (n - 1)),
        "z-max": int(ranks_for_targets(z.max(0, keepdim=True).values, [target_id])[0]),
        "z-min": int(ranks_for_targets(z.min(0, keepdim=True).values, [target_id])[0]),
    }
    for w in ORIGINAL_WEIGHTS:
        weights = torch.tensor([float(w)] + [1.0] * (n - 1)).unsqueeze(1)
        mean = torch.nn.functional.normalize((weights * vectors).sum(0, keepdim=True), dim=-1)
        out[f"mean embedding (orig x{w})"] = int(ranks_for_targets(mean @ images.T, [target_id])[0])
        rrf = (weights.double() / (RRF_CONSTANT + pos.double() + 1)).sum(0, keepdim=True)
        out[f"rrf (orig x{w})"] = int(ranks_for_targets(rrf, [target_id])[0])
    ranks = ranks_for_targets(scores, [target_id] * n).tolist()
    out["original"] = ranks[0]
    out["best of all queries (oracle*)"] = min(ranks)
    return out


def evaluate(label, examples, query_sets, retriever, path_to_id):
    """examples: (caption, target); query_sets: {strategy: {caption: [rewrites]}}."""
    rows, table = [], []
    for caption, target in examples:
        target_id = path_to_id[target]
        row = {"original": caption, "target": target}
        for name, store in query_sets.items():
            variants = store.get(caption) or []
            vectors = retriever.embed_texts([caption, *variants])
            for method, rank in methods_for(vectors, retriever.images, target_id).items():
                row[f"{name} | {method}"] = rank
        rows.append(row)
    methods = [m for m in rows[0] if " | " in m]
    print(f"\n=== {label}: {len(rows)} descriptions ===")
    width = max(map(len, methods)) + 2
    print(f"{'Strategy | method':<{width}}" + "".join(f"{f'R@{k}':>9}" for k in K_VALUES))
    last = None
    for method in methods:
        strategy = method.split(" | ")[0]
        if last and strategy != last:
            print()
        last = strategy
        ranks = [r[method] for r in rows]
        values = [recall(ranks, k) for k in K_VALUES]
        table.append({"sample": label, "method": method, **{f"recall@{k}": v for k, v in zip(K_VALUES, values)}})
        print(f"{method:<{width}}" + "".join(f"{v:>8.1f}%" for v in values))
    return rows, table


def main():
    root = Path(__file__).resolve().parent
    runs = sorted((root / "runs" / "strategies").iterdir())
    run_dir = root / "runs" / "strategies" / STRATEGY_RUN if STRATEGY_RUN else runs[-1]
    report = read_json(run_dir / "report.json")
    strategies = list(report["settings"]["strategies"])
    print(f"Reusing rewrites from {run_dir.relative_to(root)} ({', '.join(strategies)}).")

    config = read_json(root / "experiment.json")
    paths = {name: (root / value).resolve() for name, value in config.items()}
    cache = load_cache(paths["cache"], paths["manifest"])
    retriever = BlipRetriever(cache, device=DEVICE, threads=CPU_THREADS)
    path_to_id = {p: i for i, p in enumerate(cache.paths)}

    sample = [(r["original"], r["target"]) for r in report["examples"]]
    query_sets = {name: {r["original"]: r[f"{name}_variants"] for r in report["examples"]} for name in strategies}
    query_sets["ALL"] = {r["original"]: [v for name in strategies for v in r[f"{name}_variants"]]
                         for r in report["examples"]}
    results = [evaluate(f"sample of {len(sample)}", sample, query_sets, retriever, path_to_id)]

    if FULL_PARAPHRASE:
        pairs = matched_queries(read_json(paths["baseline_queries"]),
                                read_json(paths["supplied_queries"]), cache.paths)
        everything = [(p[0]["dialog"][0], p[0]["img"]) for p in pairs]
        saved = read_json(root / SAVED_PARAPHRASES)
        results.append(evaluate(f"all {len(everything)} (paraphrase only)", everything,
                                {"paraphrase": saved}, retriever, path_to_id))
    print("\n* Oracle rows use the known target to pick the best query: an upper bound, not a usable method.")

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    destination = root / "runs" / "fusion" / stamp
    destination.mkdir(parents=True)
    table = [row for _, t in results for row in t]
    with (destination / "summary.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(table[0]))
        writer.writeheader()
        writer.writerows(table)
    (destination / "report.json").write_text(json.dumps(
        {"strategy_run": str(run_dir.relative_to(root)), "original_weights": ORIGINAL_WEIGHTS,
         "rrf_constant": RRF_CONSTANT, "summary": table,
         "examples": {label: rows for label, (rows, _) in zip(["sample", "full"], results)}},
        indent=2, ensure_ascii=False), encoding="utf-8")
    (destination / "runner_snapshot.py").write_bytes(Path(__file__).read_bytes())
    print(f"\nSaved results to: {destination}")


if __name__ == "__main__":
    main()
